"""The migration, run against a real Postgres.

Marked ``integration``: it needs Docker and is excluded from the fast unit run.

Two things are verified here that cannot be checked without a database:

* the migration is reversible, and the models agree with what it creates
  (``alembic check`` finding nothing is the real assertion);
* NULL age bounds behave as *possibly eligible*. This is written as SQL rather
  than as a Python unit test on purpose, because the bug it guards against is a
  SQL one: ``min_age <= :age`` is NULL for an unknown bound, NULL is not true,
  and the row silently disappears with no error anywhere.
"""

from __future__ import annotations

from collections.abc import Iterator

import pytest
from sqlalchemy import create_engine, text
from testcontainers.community.postgres import PostgresContainer

pytestmark = pytest.mark.integration

EXPECTED_TABLES = {
    "criterion_judgments",
    "eval_runs",
    "feedback",
    "llm_calls",
    "match_runs",
    "outbox",
    "patients",
    "trial_criteria",
    "trial_matches",
    "trials",
}


@pytest.fixture(scope="module")
def migrated_db() -> Iterator[str]:
    """A Postgres container with the schema at head. Yields a sync DSN."""
    from alembic import command
    from alembic.config import Config

    with PostgresContainer(
        "postgres:17", username="beacon", password="beacon", dbname="beacon"
    ) as pg:
        host = pg.get_container_host_ip()
        port = pg.get_exposed_port(5432)

        monkey = pytest.MonkeyPatch()
        monkey.setenv("BEACON_POSTGRES__HOST", host)
        monkey.setenv("BEACON_POSTGRES__PORT", str(port))
        monkey.setenv("BEACON_POSTGRES__USER", "beacon")
        monkey.setenv("BEACON_POSTGRES__PASSWORD", "beacon")
        monkey.setenv("BEACON_POSTGRES__DATABASE", "beacon")

        from beacon_core.settings import get_settings

        get_settings.cache_clear()

        cfg = Config("alembic.ini")
        command.upgrade(cfg, "head")
        try:
            yield f"postgresql+psycopg://beacon:beacon@{host}:{port}/beacon"
        finally:
            monkey.undo()
            get_settings.cache_clear()


def test_all_ten_tables_exist(migrated_db: str) -> None:
    engine = create_engine(migrated_db)
    with engine.connect() as conn:
        rows = conn.execute(
            text(
                "select table_name from information_schema.tables "
                "where table_schema = 'public' and table_name <> 'alembic_version'"
            )
        )
        assert {r[0] for r in rows} == EXPECTED_TABLES
    engine.dispose()


def test_models_match_the_migration(migrated_db: str) -> None:
    """No drift between beacon_core.models and alembic/versions.

    If this fails, the orchestrator adds a revision. An agent never does.
    """
    from alembic import command
    from alembic.config import Config
    from alembic.util.exc import AutogenerateDiffsDetected

    cfg = Config("alembic.ini")
    try:
        command.check(cfg)
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
        pytest.fail(f"models and migrations disagree:\n{exc}")


def test_unknown_age_bounds_survive_the_filter(migrated_db: str) -> None:
    engine = create_engine(migrated_db)
    with engine.begin() as conn:
        conn.execute(
            text(
                "insert into trials (nct_id, title, conditions, interventions, locations, "
                "min_age_years, max_age_years) values "
                "('NCT_BOUNDED', 'ages 25-70', '[]', '[]', '[]', 25, 70), "
                "('NCT_UNKNOWN', 'age unparseable', '[]', '[]', '[]', null, null) "
                "on conflict (nct_id) do nothing"
            )
        )

    age = 24
    with engine.connect() as conn:
        null_safe = {
            r[0]
            for r in conn.execute(
                text(
                    "select nct_id from trials where "
                    "(min_age_years is null or min_age_years <= :age) and "
                    "(max_age_years is null or max_age_years >= :age)"
                ),
                {"age": age},
            )
        }
        naive = {
            r[0]
            for r in conn.execute(
                text(
                    "select nct_id from trials "
                    "where min_age_years <= :age and max_age_years >= :age"
                ),
                {"age": age},
            )
        }
    engine.dispose()

    # Unknown means possibly eligible, so it survives and the rule checker decides.
    assert "NCT_UNKNOWN" in null_safe
    # Positive evidence of ineligibility: 24 is genuinely outside 25-70.
    assert "NCT_BOUNDED" not in null_safe
    # The naive form drops the unknown row, with no error to notice.
    assert "NCT_UNKNOWN" not in naive
